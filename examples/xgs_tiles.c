uint8_t phase;
uint8_t frames;

void main(void) {
    xgs_init();
    for (;;) {
        xgs_frame();
        frames++;
        if ((frames & 7) == 0) {
            phase++;
            if (phase == TILES) {
                phase = 0;
            }
            for (uint8_t y = 0; y < XGS_ROWS; y++) {
                for (uint8_t x = 0; x < XGS_COLUMNS; x++) {
                    xgs_tile(x, y, (x + y + phase) % TILES);
                }
            }
        }
    }
}
